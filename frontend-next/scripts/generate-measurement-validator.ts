// Compile the published schema, never maintain a second frontend contract.
import { readFile, writeFile, unlink } from 'node:fs/promises'
import { join } from 'node:path'
import Ajv from 'ajv/dist/2020'
import standaloneCode from 'ajv/dist/standalone'
const root = join(import.meta.dir, '..')
const source = JSON.parse(
  await readFile(
    join(root, '../docs/standard/generated/cvd-2d-process-v2.schema.json'),
    'utf8',
  ),
)
// TypeScript represents UUID/date-time as strings. The API remains authoritative
// for formats; here we check object shapes, discriminants and schema constraints.
const ajv = new Ajv({
  strict: false,
  validateFormats: false,
  code: { source: true },
  inlineRefs: false,
})
const validate = ajv.compile(source.result_models.measurement_bundle)
const temp = join(root, 'src/shared/generated/.measurement-validator.cjs')
try {
  await writeFile(temp, standaloneCode(ajv, validate))
  const result = await Bun.build({
    entrypoints: [temp],
    target: 'browser',
    format: 'esm',
    minify: true,
  })
  if (!result.success) throw new Error(result.logs.join('\n'))
  await writeFile(
    join(root, 'src/shared/generated/measurement-validator.mjs'),
    '// Generated by scripts/generate-measurement-validator.ts. Do not edit.\n' +
      (await result.outputs[0].text()),
  )
  await writeFile(
    join(root, 'src/shared/generated/measurement-validator.d.mts'),
    `// Generated by scripts/generate-measurement-validator.ts. Do not edit.
import type { components } from '../types/openapi'
declare function validate(value: unknown): value is components['schemas']['MeasurementBundleCreate']
export default validate
`,
  )
} finally {
  await unlink(temp).catch(() => undefined)
}
