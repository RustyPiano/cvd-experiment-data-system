from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

from app.services.v2_field_source import (
    ARRAY_MODULE_KEYS,
    DEFAULT_FIELD_SOURCE,
    PAYLOAD_MODULE_KEYS,
    SCHEMA_VERSION,
    condition_local_key,
    load_field_source,
    payload_fields_by_module,
)

REPO_ROOT = Path(__file__).resolve().parents[3]
DEFAULT_OUTPUT = REPO_ROOT / "backend" / "app" / "schemas" / "generated" / "v2_module_payload.py"

MODULE_CLASS_NAMES = {
    "basic_info": "BasicInfoPayload",
    "target_product": "TargetProductPayload",
    "equipment": "EquipmentPayload",
    "precursors": "PrecursorsPayload",
    "substrates": "SubstratesPayload",
    "process_steps": "ProcessStepsPayload",
    "process_events": "ProcessEventsPayload",
    "pvd": "PvdPayload",
}
ITEM_CLASS_NAMES = {
    "precursors": "PrecursorItemPayload",
    "substrates": "SubstrateItemPayload",
    "process_events": "ProcessEventItemPayload",
}
STAGE_CLASS_NAMES = {
    "抽气": "EvacuationStepPayload",
    "漏检": "LeakCheckStepPayload",
    "吹扫": "PurgeStepPayload",
    "预处理": "PretreatmentStepPayload",
    "升温": "RampStepPayload",
    "温度稳定": "TemperatureStabilizationStepPayload",
    "反应生长": "GrowthStepPayload",
    "后退火": "PostAnnealStepPayload",
    "降温": "CoolingStepPayload",
    "放气": "VentStepPayload",
    "卸样": "UnloadStepPayload",
}


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Generate cvd_v2 Pydantic payload models.")
    parser.add_argument("--field-source", default=str(DEFAULT_FIELD_SOURCE))
    parser.add_argument("--output-path", default=str(DEFAULT_OUTPUT))
    return parser


def generate_v2_models(
    *,
    field_source: str | Path = DEFAULT_FIELD_SOURCE,
    output_path: str | Path = DEFAULT_OUTPUT,
) -> str:
    doc = load_field_source(str(field_source))
    rendered = render_v2_models(doc)
    target = Path(output_path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(rendered, encoding="utf-8")
    return str(target)


def render_v2_models(doc: dict[str, Any]) -> str:
    lines = [
        "# This file is generated by app.commands.generate_v2_models; do not edit.",
        "# fmt: off",
        "from __future__ import annotations",
        "",
        "from typing import Annotated, Any, Literal, Self",
        "",
        "from pydantic import BaseModel, ConfigDict, Field, model_validator",
        "",
        f'V2_MODULE_PAYLOAD_SCHEMA_VERSION = "{SCHEMA_VERSION}"',
        "",
        "",
        "def _missing(value: Any) -> bool:",
        '    return value is None or value == "" or value == [] or value == {}',
        "",
        "",
        "def _matches(value: Any, op: str, expected: Any) -> bool:",
        "    if isinstance(value, list):",
        '        if op == "eq":',
        "            return expected in value",
        '        if op == "ne":',
        "            return expected not in value",
        '        if op == "in":',
        "            return any(item in set(expected or []) for item in value)",
        '    if op == "eq":',
        "        return value == expected",
        '    if op == "ne":',
        "        return value != expected",
        '    if op == "in":',
        "        return value in set(expected or [])",
        '    raise ValueError(f"Unsupported condition op: {op}")',
        "",
        "",
        "class V2PayloadBase(BaseModel):",
        '    model_config = ConfigDict(extra="forbid")',
        "",
    ]

    grouped = payload_fields_by_module(doc)
    for module_key in PAYLOAD_MODULE_KEYS:
        if module_key == "process_steps":
            lines.extend(_render_process_step_models(doc, grouped[module_key]))
            continue
        lines.extend(_render_module_model(doc, module_key, grouped[module_key]))

    lines.extend(
        [
            "",
            "V2_MODULE_PAYLOAD_MODELS: dict[str, type[BaseModel]] = {",
            *[f'    "{key}": {MODULE_CLASS_NAMES[key]},' for key in PAYLOAD_MODULE_KEYS],
            "}",
            "",
            "",
            "def validate_v2_module_payload(",
            "    module_key: str, payload_json: dict[str, Any]",
            ") -> dict[str, Any]:",
            "    model = V2_MODULE_PAYLOAD_MODELS.get(module_key)",
            "    if model is None:",
            '        raise ValueError(f"Unsupported cvd_v2 module: {module_key}")',
            "    return model.model_validate(payload_json).model_dump(",
            '        mode="json", exclude_none=False',
            "    )",
            "",
            "",
            "V2Payload = (",
            f"    {MODULE_CLASS_NAMES[PAYLOAD_MODULE_KEYS[0]]}",
            *[f"    | {MODULE_CLASS_NAMES[key]}" for key in PAYLOAD_MODULE_KEYS[1:]],
            ")",
            "",
        ]
    )
    return "\n".join(lines)


def _render_module_model(
    doc: dict[str, Any],
    module_key: str,
    fields: list[dict[str, Any]],
) -> list[str]:
    if module_key in ARRAY_MODULE_KEYS:
        item_class = ITEM_CLASS_NAMES[module_key]
        model_class = MODULE_CLASS_NAMES[module_key]
        return [
            "",
            "",
            f"class {item_class}(V2PayloadBase):",
            *_render_field_lines(doc, fields, indent="    "),
            *_render_condition_validator(doc, fields, indent="    "),
            "",
            "",
            f"class {model_class}(V2PayloadBase):",
            f"    items: list[{item_class}] = Field(default_factory=list)",
            "",
        ]

    model_class = MODULE_CLASS_NAMES[module_key]
    return [
        "",
        "",
        f"class {model_class}(V2PayloadBase):",
        *_render_field_lines(doc, fields, indent="    "),
        *_render_condition_validator(doc, fields, indent="    "),
        "",
    ]


def _render_process_step_models(
    doc: dict[str, Any],
    fields: list[dict[str, Any]],
) -> list[str]:
    groups: dict[str, list[dict[str, Any]]] = {}
    for field in fields:
        groups.setdefault(field.get("group", "common"), []).append(field)

    lines: list[str] = []
    stage_classes: list[str] = []
    for stage in doc["stage_types"]["types"]:
        name = stage["name"]
        class_name = STAGE_CLASS_NAMES[name]
        stage_classes.append(class_name)
        allowed: list[dict[str, Any]] = []
        for group in ["common", *stage.get("shows", [])]:
            allowed.extend(groups.get(group, []))
        required_extra = set(stage.get("required_extra", []))
        lines.extend(["", "", f"class {class_name}(V2PayloadBase):"])
        lines.append(f'    stage_type: Literal["{name}"]')
        for field in allowed:
            if field["key"] == "stage_type":
                continue
            required = _field_required_for_stage(field, name, required_extra, doc)
            lines.append(_field_line(field, required=required, indent="    "))
        lines.append("")

    lines.extend(
        [
            "",
            "ProcessStepPayload = Annotated[",
            f"    {stage_classes[0]}",
            *[f"    | {class_name}" for class_name in stage_classes[1:-1]],
            f"    | {stage_classes[-1]},",
            '    Field(discriminator="stage_type"),',
            "]",
            "",
            "",
            "class ProcessStepsPayload(V2PayloadBase):",
            "    items: list[ProcessStepPayload] = Field(default_factory=list)",
            "",
            "    # Cross-entity condition 装置Setup.外场装置≠无 for field_params is enforced",
            "    # in V2ExperimentService; generated module models see only one payload.",
            "",
        ]
    )
    return lines


def _field_required_for_stage(
    field: dict[str, Any],
    stage_name: str,
    required_extra: set[str],
    doc: dict[str, Any],
) -> bool:
    if field["key"] in required_extra:
        return True
    level = field["requirement"]["level"]
    if level == "required":
        return True
    condition = field["requirement"].get("condition")
    local_key = condition_local_key(field, condition, doc)
    if local_key != "stage_type":
        return False
    return condition["op"] == "eq" and condition["value"] == stage_name


def _render_field_lines(
    doc: dict[str, Any],
    fields: list[dict[str, Any]],
    *,
    indent: str,
) -> list[str]:
    return [
        _field_line(field, required=_field_is_required(field), indent=indent) for field in fields
    ] or [f"{indent}pass"]


def _field_is_required(field: dict[str, Any]) -> bool:
    return field["requirement"]["level"] == "required"


def _field_line(field: dict[str, Any], *, required: bool, indent: str) -> str:
    type_expr = _type_expr()
    default = "" if required else " = None"
    return f"{indent}{field['key']}: {type_expr}{default}"


def _type_expr() -> str:
    # field-source.yaml still stores several formats as prose ("数组", "数值×2",
    # "下拉+多选"). P3 validates required/visible/conditional rules; stricter value
    # shapes can be generated after those formats become structured data.
    return "Any"


def _render_condition_validator(
    doc: dict[str, Any],
    fields: list[dict[str, Any]],
    *,
    indent: str,
) -> list[str]:
    checks: list[str] = []
    for field in fields:
        if field["requirement"]["level"] != "conditional_required":
            continue
        condition = field["requirement"].get("condition")
        local_key = condition_local_key(field, condition, doc)
        if local_key is None:
            continue
        op = condition["op"]
        expected = condition["value"]
        checks.extend(
            [
                (
                    f"{indent}    if _matches(self.{local_key}, {op!r}, "
                    f"{expected!r}) and _missing(self.{field['key']}):"
                ),
                f'{indent}        raise ValueError("{field["key"]} is conditionally required")',
            ]
        )
    if not checks:
        return []
    return [
        "",
        f'{indent}@model_validator(mode="after")',
        f"{indent}def _check_conditional_required(self) -> Self:",
        *checks,
        f"{indent}    return self",
    ]


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    print(generate_v2_models(field_source=args.field_source, output_path=args.output_path))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
