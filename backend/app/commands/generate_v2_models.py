def _number_type_expr(field: dict[str, Any]) -> str:
    validation = field.get("validation") or {}
    number_type = "int" if validation.get("type") == "integer" else "float"
    constraints = ["strict=True"]
    if number_type == "float":
        constraints.append("allow_inf_nan=False")
    for key in ("ge", "gt", "le", "lt"):
        if key in validation:
            constraints.append(f"{key}={validation[key]!r}")
    return f"Annotated[{number_type}, Field({', '.join(constraints)})]"


def _composite_class_name(key: str) -> str:
    return "".join(part.capitalize() for part in key.split("_")) + "Value"


def _literal_expr(options: list[str]) -> str:
    if not options:
        raise ValueError("Controlled structured field must declare options")
    return "Literal[" + ", ".join(repr(value) for value in options) + "]"


def _component_role_options(doc: dict[str, Any], fields: list[dict[str, Any]]) -> list[str]:
    components = next(field for field in fields if field["key"] == "components")
    match = re.search(r"角色[（(]([^）)]+)[）)]", str(components.get("options") or ""))
    if match is None:
        raise ValueError("components field must declare role options")
    return [
        canonical_option_value(value.strip(), doc)
        for value in match.group(1).split("·")
        if value.strip()
    ]


def _controlled_options(doc: dict[str, Any], field: dict[str, Any]) -> list[str]:
    input_type = str(field.get("input") or "")
    if not any(token in input_type for token in ("下拉", "多选")):
        return []
    ignored = {"controlled_or_other"}
    return sorted(field_option_values(field["key"], doc) - ignored)


