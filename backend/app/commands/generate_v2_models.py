def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Generate cvd_v2 Pydantic payload models.")
    parser.add_argument("--field-source", default=str(DEFAULT_FIELD_SOURCE))
    parser.add_argument("--output-path", default=str(DEFAULT_OUTPUT))
    return parser


def generate_v2_models(
    *,
    field_source: str | Path = DEFAULT_FIELD_SOURCE,
    output_path: str | Path = DEFAULT_OUTPUT,
) -> str:
    doc = load_field_source(str(field_source))
    rendered = render_v2_models(doc)
    target = Path(output_path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(rendered, encoding="utf-8")
    return str(target)


def render_v2_models(doc: dict[str, Any]) -> str:
    all_payload_fields = [
        field for fields in payload_fields_by_module(doc).values() for field in fields
    ]
    controlled_keys = sorted(
        {
            field["key"]
            for fields in payload_fields_by_module(doc).values()
            for field in fields
            if any(token in str(field.get("input") or "") for token in ("下拉", "多选"))
        }
        | {"role"}
    )
    composite_keys = sorted(
        {
            field["key"]
            for fields in payload_fields_by_module(doc).values()
            for field in fields
            if str(field.get("input") or "") in {"数值+下拉", "下拉+数值", "文本+下拉", "下拉+文本"}
        }
    )
    composite_fields = {
        field["key"]: field
        for field in all_payload_fields
        if str(field.get("input") or "") in {"数值+下拉", "下拉+数值", "文本+下拉", "下拉+文本"}
    }
    component_roles = _component_role_options(doc, all_payload_fields)
    multi_keys = sorted(
        {
            field["key"]
            for fields in payload_fields_by_module(doc).values()
            for field in fields
            if any(token in str(field.get("input") or "") for token in ("多选", "多条"))
            and field["key"] != "structure_type"
        }
    )
    lines = [
        "# This file is generated by app.commands.generate_v2_models; do not edit.",
        "# ruff: noqa: E501, F401, I001",
        "# fmt: off",
        "from __future__ import annotations",
        "",
        "from datetime import date, datetime, time",
        "from typing import Annotated, Any, Literal, Self",
        "",
        "from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator",
        "",
        "from app.services.v2_field_source import (",
        "    condition_matches as _matches,",
        "    validate_chemical_formula as _validate_formula,",
        ")",
        "",
        f'V2_MODULE_PAYLOAD_SCHEMA_VERSION = "{SCHEMA_VERSION}"',
        "",
        "",
        "def _missing(value: Any) -> bool:",
        '    return value is None or value == "" or value == [] or value == {}',
        "",
        f"_OPTION_ALIASES = {doc.get('option_codes', {})!r}",
        f"_CONTROLLED_KEYS = frozenset({tuple(controlled_keys)!r})",
        f"_COMPOSITE_KEYS = frozenset({tuple(composite_keys)!r})",
        f"_MULTI_KEYS = frozenset({tuple(multi_keys)!r})",
        "",
        "",
        "def _canonical(value: Any) -> Any:",
        "    if isinstance(value, list):",
        "        return [_canonical(item) for item in value]",
        "    if isinstance(value, str):",
        "        return _OPTION_ALIASES.get(value, value)",
        "    return value",
        "",
        "",
        "def _normalize_payload(value: Any) -> Any:",
        "    if isinstance(value, list):",
        "        return [_normalize_payload(item) for item in value]",
        "    if not isinstance(value, dict):",
        "        return value",
        "    normalized = dict(value)",
        "    for key, item in normalized.items():",
        "        if key in _COMPOSITE_KEYS:",
        "            canonical = _canonical(item)",
        "            if isinstance(item, dict):",
        "                normalized[key] = dict(item)",
        '                normalized[key]["option"] = _canonical(item.get("option"))',
        "            elif isinstance(item, (int, float)):",
        '                normalized[key] = {"value": item, "option": None}',
        "            elif canonical != item:",
        '                normalized[key] = {"value": None, "option": canonical}',
        "        elif key in _MULTI_KEYS:",
        "            canonical = _canonical(item)",
        "            normalized[key] = canonical if isinstance(canonical, list) else [canonical]",
        "        elif key in _CONTROLLED_KEYS:",
        "            normalized[key] = _canonical(item)",
        "        elif isinstance(item, (dict, list)):",
        "            normalized[key] = _normalize_payload(item)",
        "    return normalized",
        "",
        "",
        "class V2PayloadBase(BaseModel):",
        '    model_config = ConfigDict(extra="forbid")',
        "",
        "",
        "class ComponentPayload(V2PayloadBase):",
        "    formula: str",
        f"    role: {_literal_expr(component_roles)} | None = None",
        "    concentration_at_percent: "
        "Annotated[float, Field(strict=True, allow_inf_nan=False)] | None = None",
        "    layer_order: Annotated[int, Field(strict=True)] | None = None",
        "",
        '    @field_validator("formula")',
        "    @classmethod",
        "    def _formula(cls, value: str) -> str:",
        "        return _validate_formula(value)",
        "",
    ]
    for field in composite_fields.values():
        options = _controlled_options(doc, field)
        value_type = (
            "Annotated[float, Field(strict=True, allow_inf_nan=False)]"
            if "数值" in str(field.get("input") or "")
            else "str"
        )
        lines.extend(
            [
                "",
                f"class {_composite_class_name(field['key'])}(V2PayloadBase):",
                f"    value: {value_type} | None = None",
                f"    option: {_literal_expr(options)} | None = None",
            ]
        )

    grouped = payload_fields_by_module(doc)
    for module_key in PAYLOAD_MODULE_KEYS:
        if module_key == "process_steps":
            lines.extend(_render_process_step_models(doc, grouped[module_key]))
            continue
        lines.extend(_render_module_model(doc, module_key, grouped[module_key]))

    lines.extend(
        [
            "",
            "V2_MODULE_PAYLOAD_MODELS: dict[str, type[BaseModel]] = {",
            *[f'    "{key}": {MODULE_CLASS_NAMES[key]},' for key in PAYLOAD_MODULE_KEYS],
            "}",
            "",
            "",
            "def validate_v2_module_payload(",
            "    module_key: str, payload_json: dict[str, Any]",
            ") -> dict[str, Any]:",
            "    model = V2_MODULE_PAYLOAD_MODELS.get(module_key)",
            "    if model is None:",
            '        raise ValueError(f"Unsupported cvd_v2 module: {module_key}")',
            "    return model.model_validate(_normalize_payload(payload_json)).model_dump(",
            '        mode="json", exclude_none=False',
            "    )",
            "",
            "",
            "V2Payload = (",
            f"    {MODULE_CLASS_NAMES[PAYLOAD_MODULE_KEYS[0]]}",
            *[f"    | {MODULE_CLASS_NAMES[key]}" for key in PAYLOAD_MODULE_KEYS[1:]],
            ")",
            "",
        ]
    )
    return "\n".join(lines)


def _render_module_model(
    doc: dict[str, Any],
    module_key: str,
    fields: list[dict[str, Any]],
) -> list[str]:
    if module_key in ARRAY_MODULE_KEYS:
        item_class = ITEM_CLASS_NAMES[module_key]
        model_class = MODULE_CLASS_NAMES[module_key]
        return [
            "",
            "",
            f"class {item_class}(V2PayloadBase):",
            *_render_field_lines(doc, fields, indent="    "),
            *_render_field_validators(fields, indent="    "),
            *_render_condition_validator(doc, fields, indent="    "),
            "",
            "",
            f"class {model_class}(V2PayloadBase):",
            f"    items: list[{item_class}] = Field(default_factory=list)",
            "",
        ]

    model_class = MODULE_CLASS_NAMES[module_key]
    return [
        "",
        "",
        f"class {model_class}(V2PayloadBase):",
        *_render_field_lines(doc, fields, indent="    "),
        *_render_field_validators(fields, indent="    "),
        *_render_condition_validator(doc, fields, indent="    "),
        "",
    ]


def _render_process_step_models(
    doc: dict[str, Any],
    fields: list[dict[str, Any]],
) -> list[str]:
    groups: dict[str, list[dict[str, Any]]] = {}
    for field in fields:
        groups.setdefault(field.get("group", "common"), []).append(field)

    lines: list[str] = []
    stage_classes: list[str] = []
    for stage in doc["stage_types"]["types"]:
        name = stage["name"]
        class_name = STAGE_CLASS_NAMES[name]
        stage_classes.append(class_name)
        allowed: list[dict[str, Any]] = []
        for group in ["common", *stage.get("shows", [])]:
            allowed.extend(groups.get(group, []))
        required_extra = set(stage.get("required_extra", []))
        lines.extend(["", "", f"class {class_name}(V2PayloadBase):"])
        stage_code = canonical_option_value(name, doc)
        lines.append(f"    stage_type: Literal[{stage_code!r}]")
        for field in allowed:
            if field["key"] == "stage_type":
                continue
            required = _field_required_for_stage(field, name, required_extra, doc)
            lines.append(_field_line(doc, field, required=required, indent="    "))
        lines.append("")

    lines.extend(
        [
            "",
            "ProcessStepPayload = Annotated[",
            f"    {stage_classes[0]}",
            *[f"    | {class_name}" for class_name in stage_classes[1:-1]],
            f"    | {stage_classes[-1]},",
            '    Field(discriminator="stage_type"),',
            "]",
            "",
            "",
            "class ProcessStepsPayload(V2PayloadBase):",
            "    items: list[ProcessStepPayload] = Field(default_factory=list)",
            "",
            "    # Cross-entity condition 装置Setup.外场装置≠无 for field_params is enforced",
            "    # in v2_experiment_service; generated module models see only one payload.",
            "",
        ]
    )
    return lines


def _field_required_for_stage(
    field: dict[str, Any],
    stage_name: str,
    required_extra: set[str],
    doc: dict[str, Any],
) -> bool:
    if field["key"] in required_extra:
        return True
    level = field["requirement"]["level"]
    if level == "required":
        return True
    condition = field["requirement"].get("condition")
    local_key = condition_local_key(field, condition, doc)
    if local_key != "stage_type":
        return False
    return condition["op"] == "eq" and condition["value"] == stage_name


def _render_field_lines(
    doc: dict[str, Any],
    fields: list[dict[str, Any]],
    *,
    indent: str,
) -> list[str]:
    return [
        _field_line(doc, field, required=_field_is_required(field), indent=indent)
        for field in fields
    ] or [f"{indent}pass"]


def _field_is_required(field: dict[str, Any]) -> bool:
    return field["requirement"]["level"] == "required"


def _field_line(doc: dict[str, Any], field: dict[str, Any], *, required: bool, indent: str) -> str:
    type_expr = _type_expr(doc, field)
    default = "" if required else " = None"
    return f"{indent}{field['key']}: {type_expr} | None{default}"


def _type_expr(doc: dict[str, Any], field: dict[str, Any]) -> str:
    key = field["key"]
    input_type = str(field.get("input") or "")
    if key == "components":
        return "list[ComponentPayload]"
    if key == "bulk_space_group":
        return "Annotated[int, Field(strict=True, ge=1, le=230)]"
    if input_type == "数值":
        if key in {"target_layer_count", "zone_count"}:
            return "Annotated[int, Field(strict=True)]"
        return "Annotated[float, Field(strict=True, allow_inf_nan=False)]"
    if input_type == "日期时间":
        return "datetime"
    if input_type == "日期":
        return "date"
    if input_type == "时间":
        return "time"
    if input_type in {"数组", "数组(时序)"}:
        # The current UI still records these as a file/reference description. Keep the
        # trust-boundary type explicit until the dedicated uploader lands.
        return "str"
    options = _controlled_options(doc, field)
    if any(token in input_type for token in ("多选", "多条")) and key != "structure_type":
        if options:
            literal = "Literal[" + ", ".join(repr(value) for value in options) + "]"
            return f"list[{literal}]"
        return "list[str]"
    if input_type in {"数值+下拉", "下拉+数值", "文本+下拉", "下拉+文本"}:
        return _composite_class_name(key)
    if options and "其他" not in input_type:
        return "Literal[" + ", ".join(repr(value) for value in options) + "]"
    return "str"


def _composite_class_name(key: str) -> str:
    return "".join(part.capitalize() for part in key.split("_")) + "Value"


def _literal_expr(options: list[str]) -> str:
    if not options:
        raise ValueError("Controlled structured field must declare options")
    return "Literal[" + ", ".join(repr(value) for value in options) + "]"


def _component_role_options(doc: dict[str, Any], fields: list[dict[str, Any]]) -> list[str]:
    components = next(field for field in fields if field["key"] == "components")
    match = re.search(r"角色[（(]([^）)]+)[）)]", str(components.get("options") or ""))
    if match is None:
        raise ValueError("components field must declare role options")
    return [
        canonical_option_value(value.strip(), doc)
        for value in match.group(1).split("·")
        if value.strip()
    ]


def _controlled_options(doc: dict[str, Any], field: dict[str, Any]) -> list[str]:
    input_type = str(field.get("input") or "")
    if not any(token in input_type for token in ("下拉", "多选")):
        return []
    ignored = {"controlled_or_other"}
    return sorted(field_option_values(field["key"], doc) - ignored)


def _render_field_validators(fields: list[dict[str, Any]], *, indent: str) -> list[str]:
    lines: list[str] = []
    if any(field["key"] == "chemical_formula" for field in fields):
        lines.extend(
            [
                "",
                f'{indent}@field_validator("chemical_formula")',
                f"{indent}@classmethod",
                f"{indent}def _chemical_formula(cls, value: str | None) -> str | None:",
                f'{indent}    if value in (None, ""):',
                f"{indent}        return value",
                f"{indent}    return _validate_formula(value)",
            ]
        )
    if any(field["key"] == "started_at" for field in fields):
        lines.extend(
            [
                "",
                f'{indent}@field_validator("started_at", mode="before")',
                f"{indent}@classmethod",
                f"{indent}def _started_at(cls, value: Any) -> Any:",
                f"{indent}    if value is not None and not isinstance(value, str):",
                f'{indent}        raise ValueError("started_at must be an ISO datetime string")',
                f"{indent}    return value",
            ]
        )
    return lines


def _render_condition_validator(
    doc: dict[str, Any],
    fields: list[dict[str, Any]],
    *,
    indent: str,
) -> list[str]:
    checks: list[str] = []
    for field in fields:
        if field["requirement"]["level"] != "conditional_required":
            continue
        condition = field["requirement"].get("condition")
        local_key = condition_local_key(field, condition, doc)
        if local_key is None:
            continue
        op = condition["op"]
        expected = canonical_option_value(condition["value"], doc)
        checks.extend(
            [
                f"{indent}    if (",
                (
                    f"{indent}        _matches({{'op': {op!r}, 'value': {expected!r}}}, "
                    f"self.{local_key})"
                ),
                f"{indent}        and _missing(self.{field['key']})",
                f"{indent}    ):",
                f'{indent}        raise ValueError("{field["key"]} is conditionally required")',
            ]
        )
    if not checks:
        return []
    return [
        "",
        f'{indent}@model_validator(mode="after")',
        f"{indent}def _check_conditional_required(self) -> Self:",
        *checks,
        f"{indent}    return self",
    ]


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    print(generate_v2_models(field_source=args.field_source, output_path=args.output_path))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
